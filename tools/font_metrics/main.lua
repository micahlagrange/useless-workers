-- Writes the glyph advances of a font at each size the UI uses, as LOVE's own
-- FreeType measures them. tst/love_stub.lua measures text with them, so
-- tst/ui_overflow_test.lua catches text that spills. Run from the repo root:
--   "C:/Program Files/LOVE/lovec.exe" tools/font_metrics > tst/c64_metrics.lua
--   "C:/Program Files/LOVE/lovec.exe" tools/font_metrics fredoka > tst/fredoka_metrics.lua
local SETS = {
    c64 = { fonts = { c64 = 'assets/fonts/commodore64.ttf' }, sizes = { 8, 9, 10, 11, 12, 13, 14, 15, 16, 18, 26, 28, 44, 46 } },
    fredoka = { fonts = { medium = 'assets/fonts/Fredoka-Medium.ttf', semibold = 'assets/fonts/Fredoka-SemiBold.ttf' }, sizes = { 16, 20, 28, 44 } },
}

local function measure(path, sizes, indent)
    local f = assert(io.open(path, 'rb'))
    local data = love.filesystem.newFileData(f:read('*a'), 'font.ttf')
    f:close()
    local out = {}
    for _, size in ipairs(sizes) do
        local r = love.font.newRasterizer(data, size)
        local adv = {}
        for c = 32, 126 do adv[#adv + 1] = tostring(r:getGlyphData(string.char(c)):getAdvance()) end
        out[#out + 1] = string.format('%s[%d] = { height = %d, advance = { %s } },', indent, size, r:getHeight(), table.concat(adv, ', '))
    end
    return out
end

function love.load(args)
    local which = 'c64'
    for _, a in ipairs(args or {}) do if SETS[a] then which = a end end
    local set = SETS[which]
    local out = { '-- Generated by tools/font_metrics (' .. which .. '). Do not edit.', '-- advance[i] is the width of string.char(31 + i).', 'return {' }
    if which == 'c64' then
        for _, l in ipairs(measure(set.fonts.c64, set.sizes, '    ')) do out[#out + 1] = l end
    else
        for _, name in ipairs({ 'medium', 'semibold' }) do
            out[#out + 1] = '    ' .. name .. ' = {'
            for _, l in ipairs(measure(set.fonts[name], set.sizes, '        ')) do out[#out + 1] = l end
            out[#out + 1] = '    },'
        end
    end
    out[#out + 1] = '}'
    io.write(table.concat(out, '\n') .. '\n')
    love.event.quit()
end
