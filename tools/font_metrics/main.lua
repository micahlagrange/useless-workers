-- Writes tst/c64_metrics.lua: the advance of every printable ASCII glyph of
-- the C64 face at each size the UI uses, as LOVE's own FreeType measures it.
-- tst/ui_overflow_test.lua measures text with it. Run from the repo root:
--   "C:/Program Files/LOVE/lovec.exe" tools/font_metrics > tst/c64_metrics.lua
local FONT = 'assets/fonts/commodore64.ttf'
local SIZES = { 8, 9, 10, 11, 12, 13, 14, 15, 16, 18, 26, 28, 44, 46 }

function love.load()
    local f = assert(io.open(FONT, 'rb'))
    local data = love.filesystem.newFileData(f:read('*a'), 'c64.ttf')
    f:close()
    local out = { '-- Generated by tools/font_metrics from ' .. FONT .. '. Do not edit.', '-- advance[i] is the width of string.char(31 + i).', 'return {' }
    for _, size in ipairs(SIZES) do
        local r = love.font.newRasterizer(data, size)
        local adv = {}
        for c = 32, 126 do adv[#adv + 1] = tostring(r:getGlyphData(string.char(c)):getAdvance()) end
        out[#out + 1] = string.format('    [%d] = { height = %d, advance = { %s } },', size, r:getHeight(), table.concat(adv, ', '))
    end
    out[#out + 1] = '}'
    io.write(table.concat(out, '\n') .. '\n')
    love.event.quit()
end
